CREATE TABLE IF NOT EXISTS order_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 event_key VARCHAR(120) NOT NULL,
 title VARCHAR(120) NOT NULL,
 detail TEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(order_id,event_key),FOREIGN KEY(order_id) REFERENCES orders(id)
);
CREATE TABLE IF NOT EXISTS invoices (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL UNIQUE,
 number VARCHAR(60) NOT NULL UNIQUE,
 snapshot MEDIUMTEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id)
);
CREATE TABLE IF NOT EXISTS order_emails (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 event_key VARCHAR(120) NOT NULL,
 recipient VARCHAR(190) NOT NULL,
 subject VARCHAR(255) NOT NULL,
 body TEXT NOT NULL,
 invoice_id BIGINT UNSIGNED NULL,
 state ENUM('pending','sending','sent','failed') NOT NULL DEFAULT 'pending',
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 last_error VARCHAR(255) NOT NULL DEFAULT '',
 sent_at DATETIME NULL,
 attempted_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(order_id,event_key),FOREIGN KEY(order_id) REFERENCES orders(id),FOREIGN KEY(invoice_id) REFERENCES invoices(id)
);
